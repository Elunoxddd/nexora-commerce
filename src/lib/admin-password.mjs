import { randomBytes, scrypt, scryptSync, timingSafeEqual } from "node:crypto";
import { promisify } from "node:util";

const scryptAsync = promisify(scrypt);
const SCRYPT_OPTIONS = { N: 16_384, r: 8, p: 1, maxmem: 64 * 1024 * 1024 };

export function hashAdminPassword(password) {
  if (typeof password !== "string" || password.length < 12 || password.length > 256) {
    throw new Error("La clave debe tener entre 12 y 256 caracteres.");
  }
  const salt = randomBytes(16);
  const derived = scryptSync(password, salt, 64, SCRYPT_OPTIONS);
  // Colon separators avoid dotenv's `$VARIABLE` expansion in .env.local.
  return `scrypt:16384:8:1:${salt.toString("hex")}:${derived.toString("hex")}`;
}

function normalizeHash(value) {
  let encoded = value.trim();
  encoded = encoded.replace(/^ADMIN_PASSWORD_HASH\s*=\s*/i, "").trim();
  if ((encoded.startsWith('"') && encoded.endsWith('"')) || (encoded.startsWith("'") && encoded.endsWith("'"))) {
    encoded = encoded.slice(1, -1);
  }
  // Accept hashes generated by the previous script version.
  if (encoded.startsWith("scrypt$")) encoded = encoded.replaceAll("$", ":");
  return encoded;
}

export async function verifyAdminPasswordHash(password, value) {
  if (typeof password !== "string" || password.length < 1 || password.length > 256 || typeof value !== "string") return false;
  const parts = normalizeHash(value).split(":");
  if (parts.length !== 6 || parts[0] !== "scrypt" || parts[1] !== "16384" || parts[2] !== "8" || parts[3] !== "1") return false;

  const [, , , , salt, expectedHex] = parts;
  if (!/^[a-f\d]{32}$/i.test(salt) || !/^[a-f\d]{128}$/i.test(expectedHex)) return false;
  try {
    const actual = await scryptAsync(password, Buffer.from(salt, "hex"), 64, SCRYPT_OPTIONS);
    return timingSafeEqual(actual, Buffer.from(expectedHex, "hex"));
  } catch {
    return false;
  }
}
